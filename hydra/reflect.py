"""`hydra reflect` (A6) — turn recurring corrections into role lessons.

After some runs, scan `.hydra/runs/*/` for what went wrong, group the failures
by the role of the task that hit them, and write
`.hydra/roles/<role>.lessons.md`. `load_role` prepends that file to the role's
prompt on the next run.

This is explicit and revertable — a text file you can read and edit — not a
black-box weight update. If a driver is available it summarises; otherwise it
just lists the distinct failure reasons.
"""
from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

from .drivers import Driver
from .tasks import load_tasks

_LESSON_HEADER = "<!-- generated by `hydra reflect` — edit or delete freely -->\n"


def _role_of(task_file: str, task_id: str) -> str:
    try:
        for t in load_tasks(task_file):
            if t.id == task_id:
                return t.role or "coder"
    except Exception:
        pass
    return "coder"


def gather_failures(root: str | Path) -> dict[str, list[str]]:
    runs = Path(root) / ".hydra" / "runs"
    by_role: dict[str, list[str]] = defaultdict(list)
    if not runs.is_dir():
        return {}
    for run_dir in sorted(runs.glob("*")):
        state_f = run_dir / "state.json"
        if not state_f.is_file():
            continue
        try:
            st = json.loads(state_f.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        tf = st.get("task_file", "")
        for tid, t in st.get("tasks", {}).items():
            err = (t.get("error") or "").strip()
            if t.get("status") == "failed" and err:
                by_role[_role_of(tf, tid)].append(err)
    return dict(by_role)


def _distinct(reasons: list[str]) -> list[str]:
    seen, out = set(), []
    for r in reasons:
        key = re.sub(r"\d+", "N", r.lower())[:80]
        if key not in seen:
            seen.add(key)
            out.append(r)
    return out


def reflect(root: str | Path, *, driver: Driver | None = None) -> dict[str, Path]:
    root = Path(root)
    failures = gather_failures(root)
    written: dict[str, Path] = {}
    roles_dir = root / ".hydra" / "roles"
    for role, reasons in failures.items():
        distinct = _distinct(reasons)
        if not distinct:
            continue
        if driver is not None and driver.available() and len(distinct) > 1:
            body = _summarise(role, distinct, driver)
        else:
            body = "\n".join(f"- Avoid: {r}" for r in distinct)

        roles_dir.mkdir(parents=True, exist_ok=True)
        base = roles_dir / f"{role}.md"
        existing = base.read_text(encoding="utf-8") if base.exists() else _builtin_role(role)
        lessons_path = roles_dir / f"{role}.lessons.md"
        lessons_path.write_text(
            _LESSON_HEADER + f"# Lessons for the {role} role\n\n" + body + "\n",
            encoding="utf-8")
        # ensure the role file itself exists so overrides + lessons compose
        if not base.exists():
            base.write_text(existing, encoding="utf-8")
        written[role] = lessons_path
    return written


def _builtin_role(role: str) -> str:
    from .roles import load_role
    try:
        return load_role(".", role)
    except Exception:
        return f"You are the {role}."


def _summarise(role: str, reasons: list[str], driver: Driver) -> str:
    prompt = (
        f"These are failures the '{role}' agent hit across past runs. Write 3-6 "
        f"terse imperative lessons ('Always…', 'Never…', 'Check…') to prepend to "
        f"its prompt so it avoids repeating them. One per line, no preamble.\n\n"
        + "\n".join(f"- {r}" for r in reasons))
    res = driver.run(prompt, ".", 180)
    if res.ok and res.stdout.strip():
        return res.stdout.strip()
    return "\n".join(f"- Avoid: {r}" for r in reasons)
